/**
 * Scan assets/*.png and emit src/catalogue.generated.ts
 * Run: node tools/generate-catalogue.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const dir = ["assets"]
const assetsDirs = dir.map(d => path.join(root, d));

const WALL_HINTS = [
  "tile-wall",
  "tile-grating",
  "clock",
  "sign",
  "gauge",
  "billboard",
  "navlight",
  "valve",
  "level-bar",
  "warning-stripe",
  "wide-console-3x1",
  "vent",
  "light",
  "lamp",
  "window",
  "hud",
  "panel-wall",
];

function categoryFor(id) {
  const size = id.includes("1x1") ? "-1" 
  : id.includes("2x2") ? "-2"  
  : id.includes("3x3") ? "-3" 
  : "-X"
  console.log('ID == ', id, size)
  if (id.startsWith("char-")) return "char" + size;
  if (id.startsWith("icon-arrow-") || id.startsWith("icon-cheveron")) return "arraw" + size;
  if (id.startsWith("icon-")) return "icon" + size;

  if (id.startsWith("garden-")) return "garden" + size;
  if (id.startsWith("home-")) return "home" + size;
  if (id.startsWith("ind-") || id.startsWith("logi-")) return "indus" + size;
  if (id.startsWith("logi-") || id.startsWith("logi-")) return "logistic" + size;
  if (id.startsWith("wide-") || id.startsWith("wide-")) return "wide" + size;
  if (id.startsWith("tile")) return "walls" + size;
  if (id.startsWith("space-") || id.includes("habitat") || id.includes("airlock")) return "space" + size;

  const start = id.split("-")[0]
  return start + size

  // return "props" + size;
}

function alignFor(id) {
  const lower = id.toLowerCase();
  if (WALL_HINTS.some((h) => lower.includes(h))) return "wall";
  return "floor";
}

function labelFor(id) {
  return id
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function parseFile(file) {
  const stem = file.replace(/\.png$/i, "");
  const m = file.match(/^(.+)-(\d+)x(\d+)\.png$/i);
  if (m) {
    return { baseId: stem, cellsW: Number(m[2]), cellsH: Number(m[3]), file, stem, hasSize: false };
  }
  return { baseId: stem, cellsW: 1, cellsH: 1, file, stem, hasSize: false };
}

const files = 
  assetsDirs.map(d => fs.readdirSync(d).filter((f) => f.toLowerCase().endsWith(".png"))).flat()
;
const PX = 16;

// Many objects ship multiple cell-sizes (e.g. home-bed-2x2 / home-bed-3x2 /
// home-bed-3x3). Those share the same base id, which collapsed them into a
// single structure type and broke per-variant selection in the picker. Count
// base ids and suffix the duplicates with their size to keep every sprite
// independently selectable.
const parsedFiles = files.map(parseFile);
const baseCounts = new Map();
for (const p of parsedFiles) {
  baseCounts.set(p.baseId, (baseCounts.get(p.baseId) ?? 0) + 1);
}

const items = parsedFiles.map((p) => {
  const collides = baseCounts.get(p.baseId) > 1;
  // Duplicate base ids are disambiguated with the cell-size suffix carried in
  // the filename; unique base ids keep their clean name.
  const id = collides
    ? p.hasSize
      ? p.stem
      : `${p.baseId}-${p.cellsW}x${p.cellsH}`
    : p.baseId;
  const category = categoryFor(p.baseId);
  return {
    id,
    label: labelFor(id),
    category,
    width: p.cellsW * PX,
    height: p.cellsH * PX,
    file: p.file,
    align: alignFor(p.baseId),
  };
});

items.sort((a, b) => a.category.localeCompare(b.category) || a.label.localeCompare(b.label));

const categoryIds = [...new Set(items.map((i) => i.category))].sort();
const categories = categoryIds.map((id) => ({
  id,
  label: id.charAt(0).toUpperCase() + id.slice(1),
}));

const menu = {
  id: "icons",
  label: "Icons",
  category: "glyphs",
  width: 16,
  height: 16,
  file: "char-A-1x1.png",
  align: "wall",
};

if (!items.some((i) => i.id === menu.id)) {
  items.unshift(menu);
}

const out = `/** AUTO-GENERATED by tools/generate-catalogue.mjs — do not edit */
import type { CatalogueCategory, CatalogueItem } from "../../../packages/catalogue/src/list/index.ts";

export const ICON_CATEGORIES: CatalogueCategory[] = ${JSON.stringify(categories, null, 2)};

export const ICON_ITEMS: CatalogueItem[] = ${JSON.stringify(
  items.map(({ id, label, category, width, height, file, align }) => ({
    id,
    label,
    category,
    width,
    height,
    file,
    align,
    description: "Decorative. No collision.",
  })),
  null,
  2,
)};

export const ICON_FILES: { id: string; file: string }[] = ${JSON.stringify(
  items.map(({ id, file }) => ({ id, file })),
  null,
  2,
)};
`;

fs.writeFileSync(path.join(root, "src", "catalogue.generated.ts"), out, "utf8");
console.log(`Wrote ${items.length} items in ${categories.length} categories`);
