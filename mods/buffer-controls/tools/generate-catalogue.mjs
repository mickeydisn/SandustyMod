/**
 * Scan assets/*.png (and assets2/*.png) and emit src/catalogue.generated.ts
 * Run: node tools/generate-catalogue.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const ASSET_DIRS = ["assets"];
const PX = 16;

const WALL_HINTS = [
  "tile-wall",
  "tile-grating",
  "clock",
  "sign",
  "gauge",
  "billboard",
  "navlight",
  "valve",
  "level-bar",
  "warning-stripe",
  "wide-console-3x1",
  "vent",
  "light",
  "lamp",
  "window",
  "hud",
  "panel-wall",
];

/** Derive the "<name><size>" category suffix (e.g. "char-2") from an id. */
function sizeSuffix(id) {
  if (id.includes("1x1")) return "_1";
  if (id.includes("2x2")) return "_2";
  if (id.includes("3x3")) return "_3";
  return "__";
}

function categoryFor(id) {
  const size = sizeSuffix(id);

  if (id.startsWith("char-")) return "char" + size;
  if (id.startsWith("icon-arrow-") || id.startsWith("icon-cheveron")) return "arraw" + size;
  if (id.startsWith("icon-")) return "icon" + size;
  if (id.startsWith("garden-")) return "garden" + size;
  if (id.startsWith("home-")) return "home" + size;
  if (id.startsWith("ind-") || id.startsWith("logi-")) return "indus" + size;
  if (id.startsWith("logi-")) return "logistic" + size;
  if (id.startsWith("wide-")) return "wide" + size;
  if (id.startsWith("tile")) return "walls" + size;
  if (id.startsWith("space-") || id.includes("habitat") || id.includes("airlock")) return "space" + size;

  return id.split("-")[0] + size;
}

function alignFor(id) {
  const lower = id.toLowerCase();
  return WALL_HINTS.some((hint) => lower.includes(hint)) ? "wall" : "floor";
}

function labelFor(id) {
  return id
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

/** Parse a filename into its base id and cell dimensions, e.g. "home-bed-3x2.png" -> { baseId: "home-bed", cellsW: 3, cellsH: 2 }. */
function parseFile(file, dir) {
  const stem = file.replace(/\.png$/i, "");
  const match = file.match(/^(.+)-(\d+)x(\d+)\.png$/i);
  const cellsW = match ? Number(match[2]) : 1;
  const cellsH = match ? Number(match[3]) : 1;
  return { baseId: stem, cellsW, cellsH, file, dir, path: `./${dir}/${file}` };
}

// Gather every PNG across all asset directories, keeping track of which
// directory each file came from so we can emit its full relative path.
const parsedFiles = ASSET_DIRS.flatMap((dir) => {
  const dirPath = path.join(root, dir);
  return fs
    .readdirSync(dirPath)
    .filter((f) => f.toLowerCase().endsWith(".png"))
    .map((f) => parseFile(f, dir));
});

// Many objects ship multiple cell-sizes (e.g. home-bed-2x2 / home-bed-3x2 /
// home-bed-3x3). Those share the same base id, which would collapse them
// into a single structure type and break per-variant selection in the
// picker. Count base ids and suffix the duplicates with their size so every
// sprite stays independently selectable.
const baseCounts = new Map();
for (const p of parsedFiles) {
  baseCounts.set(p.baseId, (baseCounts.get(p.baseId) ?? 0) + 1);
}

const items = parsedFiles
  .map((p) => {
    const isDuplicate = baseCounts.get(p.baseId) > 1;
    const id = isDuplicate ? `${p.baseId}-${p.cellsW}x${p.cellsH}` : p.baseId;
    return {
      id,
      label: labelFor(id),
      category: categoryFor(p.baseId),
      width: p.cellsW * PX,
      height: p.cellsH * PX,
      file: p.path.slice(2),
      align: alignFor(p.baseId),
    };
  })
  .sort((a, b) => a.category.localeCompare(b.category) || a.label.localeCompare(b.label));

const categoryIds = [...new Set(items.map((i) => i.category))].sort();
const categories = categoryIds.map((id) => ({
  id,
  label: id.charAt(0).toUpperCase() + id.slice(2),
}));

// The catalogue always needs an "icons" menu entry; reuse whichever asset
// directory actually contains char-A-1x1.png so the path stays accurate.
const menuSource = parsedFiles.find((p) => p.baseId === "char-A-1x1");
const menu = {
  id: "icons",
  label: "Icons",
  category: "glyphs",
  width: 16,
  height: 16,
  file:  `${ASSET_DIRS[0]}/char-A-1x1.png`, //  menuSource ? menuSource.path : `${ASSET_DIRS[0]}/char-A-1x1.png`,
  align: "wall",
};

if (!items.some((i) => i.id === menu.id)) {
  items.unshift(menu);
}

const out = `/** AUTO-GENERATED by tools/generate-catalogue.mjs — do not edit */
import type { CatalogueCategory, CatalogueItem } from "@sandmd/catalogue";

export const ICON_CATEGORIES: CatalogueCategory[] = ${JSON.stringify(categories, null, 2)};

export const ICON_ITEMS: CatalogueItem[] = ${JSON.stringify(
  items.map(({ id, label, category, width, height, file, align }) => ({
    id,
    label,
    category,
    width,
    height,
    file,
    align,
    description: "Decorative. No collision.",
  })),
  null,
  2,
)};

export const ICON_FILES: { id: string; file: string }[] = ${JSON.stringify(
  items.map(({ id, file }) => ({ id, file })),
  null,
  2,
)};
`;

fs.writeFileSync(path.join(root, "src", "catalogue.generated.ts"), out, "utf8");
console.log(`Wrote ${items.length} items in ${categories.length} categories`);
